// Copies each project's real UI into public/demos/<name>/ so the portfolio's
// demos always match the app. Runs before `npm run dev` and `npm run build`.
//
// - app.js and app.css are copied byte for byte.
// - index.html gets three small changes: asset paths made relative, the
//   demo's fake backend (demo/mock.js) loaded first, and a "Demo" badge.
// - Every /api/... path the UI uses is checked against the routes the mock
//   handles, so a UI change that needs a new endpoint is reported here
//   instead of silently breaking the demo.
//
// The source repo is looked up next to this one (../podcast-recaps) or at
// $PODCAST_RECAPS_DIR. Where it doesn't exist (Vercel, other machines) the
// sync is skipped and the copies already committed in public/ are used.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  copyFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const demos = [
  {
    name: "podcast-recaps",
    source:
      process.env.PODCAST_RECAPS_DIR ?? resolve(root, "../podcast-recaps"),
    uiDir: "src/ui",
  },
];

let problems = 0;

for (const demo of demos) {
  const from = join(demo.source, demo.uiDir);
  const to = join(root, "public/demos", demo.name);
  if (!existsSync(join(from, "index.html"))) {
    console.log(
      `[sync-demos] ${demo.name}: no source at ${from}, using the committed copy.`,
    );
    continue;
  }
  mkdirSync(to, { recursive: true });

  copyFileSync(join(from, "app.js"), join(to, "app.js"));
  copyFileSync(join(from, "app.css"), join(to, "app.css"));

  let html = readFileSync(join(from, "index.html"), "utf8");
  const edits = [
    // Served from /demos/<name>/, not the site root.
    [/href="\/app\.css"/, 'href="app.css"'],
    [/src="\/app\.js"/, 'src="app.js"'],
    // The fake backend has to patch fetch before app.js runs.
    [
      /<script type="module"/,
      '<script src="demo/mock.js"></script>\n  <script type="module"',
    ],
    [
      /<\/body>/,
      '  <div class="demo-badge" title="Everything here is fake data that runs in your browser. Nothing is sent anywhere.">Demo · sample data</div>\n  <link rel="stylesheet" href="demo/demo.css">\n</body>',
    ],
  ];
  for (const [pattern, replacement] of edits) {
    if (!pattern.test(html)) {
      console.warn(
        `[sync-demos] ${demo.name}: index.html no longer matches ${pattern}; update scripts/sync-demos.mjs.`,
      );
      problems++;
      continue;
    }
    html = html.replace(pattern, replacement);
  }
  // The note goes after the doctype; anything before it puts browsers in quirks mode.
  const note = `<!-- Generated by scripts/sync-demos.mjs from ${demo.name}/${demo.uiDir}/index.html. Edit the source, not this copy. -->`;
  writeFileSync(
    join(to, "index.html"),
    html.replace(/^(\s*<!doctype[^>]*>)/i, `$1\n${note}`),
  );

  // Compare the endpoints the UI uses with the ones the mock implements.
  const uiPaths = new Set(
    [
      ...readFileSync(join(from, "app.js"), "utf8").matchAll(
        /["`](\/api\/[^"`?]*)/g,
      ),
    ].map(([, path]) => normalize(path)),
  );
  const mockPaths = new Set(
    [
      ...readFileSync(join(to, "demo/mock.js"), "utf8").matchAll(
        /"(?:GET|POST|PUT|DELETE) (\/api\/[^"]*)"/g,
      ),
    ].map(([, path]) => normalize(path)),
  );
  const missing = [...uiPaths].filter((path) => !mockPaths.has(path));
  if (missing.length) {
    problems += missing.length;
    console.warn(
      `[sync-demos] ${demo.name}: the UI calls endpoints the demo doesn't handle yet:`,
    );
    for (const path of missing)
      console.warn(
        `  ${path}   -> add a route in public/demos/${demo.name}/demo/mock.js`,
      );
  } else {
    console.log(
      `[sync-demos] ${demo.name}: synced; all ${uiPaths.size} endpoints are covered by the demo.`,
    );
  }
}

if (problems)
  console.warn(
    `[sync-demos] ${problems} problem(s) above. The demo may be partly broken until they're fixed.`,
  );

/** "/api/shows/${id}/feed" and "/api/shows/:id/feed" both become "/api/shows/:/feed". */
function normalize(path) {
  return path
    .replace(/\$\{[^}]*\}/g, ":")
    .replace(/:[a-zA-Z]+/g, ":")
    .replace(/\/$/, "");
}
